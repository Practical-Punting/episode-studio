def visible_text(page):
    """The words a viewer actually sees — tags, head, script and style removed."""
    body = re.sub(r"<head.*?</head>|<script.*?</script>|<style.*?</style>", " ",
                  page, flags=re.S)
    return norm(re.sub(r"<[^>]+>", " ", html.unescape(body))).lower()


def assert_measured_items_show_a_figure(card, blk):
    """🔴 THE OTHER HALF OF THE GUARD, AND THE ONE THAT WAS MISSING.

    🔵 IT TAKES NO PAGE, AND THAT IS WHY IT CAN RUN AT THE COMMISSION. It used to
    accept one and compute `visible_text(page)` into a variable nothing ever read —
    so it LOOKED like a render-time check and was filed with the two that genuinely
    are. It is pure episode.json, it always was, and preflight_cards calls it at
    audit_inputs on the strength of that (11 Aug 2026).

    `assert_no_invented_text` proves nothing appears that is not in the file. NOTHING
    proved the reverse — that a number the card is ABOUT reaches the screen at all.

    EP18 C9, 8 Aug 2026: the `bars` block uses {{ITEM.value}} for {{WIDTH}} only, the
    bar's LENGTH, and never draws it as text. C9's notes read "per cent profit on
    turnover" with no number in front, so the finished video showed two bars and a
    dangling phrase. `check_trace` passed, correctly — 5 and 12 both trace. It had
    verified the DATA and nobody had looked at the PICTURE.

    ⚠️ THE RULE IS PER ITEM, NOT PER FIGURE, AND THE NARROWING IS THE WHOLE POINT.
    The first version demanded that EVERY figure appear on screen, and it halted EP18's
    C3 — an episode that shipped and is right. C3 draws win counts as bar LENGTHS and
    labels them with strike rates: the measurement is the picture, the note is the
    number, and the viewer is well served. Demanding both would ban a good card.
    What cannot stand is an item that carries a measurement and shows NO figure at all:
    a bar, and a caption with a hole where the number should be.

    Which fields are measurement-only is read from the BLOCK'S OWN SCHEMA (`numeric`),
    so a block added tomorrow is covered without anyone listing it here.

    ⚠️ A FIGURE SPELLED OUT IS STILL A FIGURE (11 Aug 2026). The first version tested
    for a DIGIT, and on EP17 C3 — win counts drawn as bars, captioned "Sixteen per
    cent" / "Ten per cent" / "Five per cent" — it reported a card that shows three
    figures as showing none. That is precisely the shape the paragraph above BLESSES:
    the measurement is the picture, the note is the number. It surfaced when this
    check was wired into the commission, where a wrong halt costs three repair
    cycles rather than one look at a run log.
        THE COST OF THE WIDENING, NAMED: a caption that merely contains the word
    "one" or "hundred" as prose now counts as showing a figure, so a genuinely empty
    caption could slip through on a coincidence. That is the cheaper mistake. A guard
    that halts a good episode is the version somebody switches off (CLAUDE.md 4a),
    and the four real catches — EP14 C8, EP17 (none), EP18 C9, EP20 C5 — all still
    fire, because "lengths behind the leader", "per cent profit on turnover" and
    "variables" contain no number in any spelling.
    """
    content = card.get("content") or {}
    lists = (blk.get("schema") or {}).get("lists", {})
    # 🔴 EVERY OFFENDING ITEM, IN ONE MESSAGE. (EP21, 11 Aug 2026.)
    # This used to `raise` on the FIRST one, and that turned a bounded repair loop
    # into whack-a-mole. EP21's C9 had BOTH bars unlabelled; the writer was told only
    # about "Randwick", fixed it, resubmitted, was told about "Rosehill", and the
    # three attempts ran out on ONE CARD. The engine then halted saying — correctly —
    # that retrying would not help.
    #     EP20's C5 was the same shape and only survived because a human fixed both
    # bars by hand while looking at the one it named.
    # The rule was already written down, in _epjson_gate: "The writer gets every
    # complaint at once." A checker that reports one fault per attempt cannot be used
    # inside a loop with three attempts.
    bad = []
    for name, spec in lists.items():
        numeric = set(spec.get("numeric", []))
        if not numeric:
            continue                     # nothing here is measurement-only
        # ⚠️ "MEASUREMENT-ONLY" WAS AN ASSUMPTION ABOUT EVERY BLOCK, AND `ladder`
        # BREAKS IT. This check's whole premise — written into its own halt message —
        # is that "a list's numeric field sets the bar LENGTH only, it is never
        # rendered as text". True of `bars`, where the number reaches the screen
        # solely through the note beside it. NOT true of the ladder, whose figure IS
        # the label above its bar: 50.0 is drawn at 68px Anton and is the single
        # biggest thing on the card. Left unstated, this would have halted the ladder
        # for showing no figure while showing seven of them.
        #     READ FROM THE BLOCK'S OWN SCHEMA, like `numeric` beside it, so a block
        # added tomorrow declares its own answer instead of being listed here.
        if spec.get("shows_numeric"):
            continue
        for i, item in enumerate(content.get(name) or [], 1):
            if not isinstance(item, dict):
                continue
            measured = [item.get(k) for k in numeric if str(item.get(k) or "").strip()]
            if not measured:
                continue                 # nothing being measured, nothing to show
            shown = [v for k, v in item.items()
                     if k not in numeric and isinstance(v, str) and shows_a_figure(v)]
            if shown:
                continue
            label = item.get("label") or item.get("k") or f"{name}[{i}]"
            bad.append(f"{name}[{i}] ({label!r}), drawn as a measurement of "
                       f"{measured[0]!r}")
    if bad:
        one = len(bad) == 1
        lead = ("this item is drawn as a measurement and shows NO figure anywhere a "
                "viewer can read it" if one else
                f"these {len(bad)} items are drawn as measurements and show NO figure "
                f"anywhere a viewer can read them")
        raise Halt(
            f"card {card.get('id')}: {lead} — " + "; ".join(bad) + ". "
            "A list's numeric field sets the bar LENGTH only — it is never rendered as "
            "text — so the number reaches the screen solely through the item's other "
            "fields, and none of them has one. EP18 C9 shipped exactly this: two bars "
            'and "per cent profit on turnover" with nothing in front. Its notes became '
            '"5 per cent profit on turnover". '
            + ("" if one else "FIX THEM ALL: they are listed together on purpose, "
                              "because fixing one and resubmitting spends an attempt "
                              "and comes straight back."))


def assert_no_invented_text(page, card, frame_tpl, blk):
    """Post-hoc proof of guard 3: every visible word came from the file.

    Strip the generated page back to its visible text and check that each word
    of it appears either in a template literal or in a content value. If this
    ever fires it means a code path produced prose, which must not exist.
    """
    body = re.sub(r"<head.*?</head>|<script.*?</script>|<style.*?</style>", " ",
                  page, flags=re.S)
    visible = norm(re.sub(r"<[^>]+>", " ", html.unescape(body))).lower()
    allowed = norm(html.unescape(re.sub(r"<[^>]+>", " ",
                   frame_tpl + blk["markup"]))).lower()
    for _, v in walk_values(card["content"]):
        if isinstance(v, str):
            allowed += " " + norm(html.unescape(re.sub(r"<[^>]+>", " ", v))).lower()
    for fld in ("eyebrow", "headline_display", "headline"):
        if card.get(fld):
            allowed += " " + norm(card[fld]).lower()
    # A list's 1-based position number ({{I}}) is generated by the template, not
    # authored — the `steps` ladder prints it. It is not prose and cannot be
    # fabricated: it is bounded by the length of the list in episode.json.
    for v in (card["content"] or {}).values():
        if isinstance(v, list):
            allowed += " " + " ".join(str(i) for i in range(1, len(v) + 1))
    # The rail's captions and numbers are episode.json data exactly like content is.
    rail = card.get("rail") or {}
    for lab in (rail.get("labels") or []):
        allowed += " " + norm(str(lab)).lower()
    for k in ("n", "of"):
        if rail.get(k) is not None:
            allowed += " " + str(rail[k])
    stray = [w for w in visible.split() if w and w not in allowed]
    if stray:
        raise Halt(f"card {card['id']}: generated page contains text that is in NEITHER the "
                   f"template nor episode.json: {stray[:8]}. This is a generator bug — "
                   f"the substitution engine must never originate prose.")


