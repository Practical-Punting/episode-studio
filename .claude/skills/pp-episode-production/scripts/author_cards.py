def source_article_raw(ep_json, ep_dir):
    """The verbatim source article named in episode.json -> source, AS WRITTEN.

    Split out from source_article_text because a lift needs the RAW file: a
    markdown table's row structure lives entirely in its newlines, and `norm()`
    collapses them. Same lookup, one implementation, two readings — which is the
    same split `author_ebook` makes between article_blocks and article_paragraphs,
    and for the identical reason.
    """
    src = ep_json.get("source", "")
    m = re.search(r"(docs/[\w\-.]+\.md)", src)
    if not m:
        raise Halt("episode.json -> source does not name a 'Verbatim source: docs/....md' file, "
                   "so no figure can be traced. Trace-or-halt cannot be satisfied.")
    rel = m.group(1)
    for base in (os.path.dirname(os.path.dirname(os.path.abspath(ep_dir))), ep_dir):
        p = os.path.join(base, rel)
        if os.path.exists(p):
            return open(p, encoding="utf-8").read()
    raise Halt(f"source article {rel!r} named in episode.json was not found on disk")


def source_article_text(ep_json, ep_dir):
    """Find the verbatim source article named in episode.json -> source."""
    return norm(source_article_raw(ep_json, ep_dir))


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("episode_json")
    ap.add_argument("out_dir")
    ap.add_argument("--only", help="comma-separated card ids")
    ap.add_argument("--force", action="store_true",
                    help="regenerate pages that already carry the generated marker")
    a = ap.parse_args()

    ep_dir = os.path.dirname(os.path.abspath(a.episode_json))
    ep = json.load(open(a.episode_json, encoding="utf-8"))
    raw_article = source_article_raw(ep, ep_dir)
    article = norm(raw_article)
    only = set(a.only.split(",")) if a.only else None

    cards = [c for c in ep.get("cards", []) if c.get("block")]
    if only:
        cards = [c for c in cards if c["id"] in only]

    # 🔴 THE LIFT RUNS FIRST, BEFORE ONE GATE LOOKS AT ONE CARD. A lifted card is
    # INCOMPLETE in episode.json on purpose — its rows are an empty slot — so a
    # schema check run before the fill would report a card with no rows, which is
    # true and useless. Filling first means every gate downstream sees the card a
    # viewer will see, and none of them needs to know a lift happened.
    lifted = apply_lifts(cards, raw_article)
    if lifted:
        print(f"lifted the data for {len(lifted)} card(s) straight out of the "
              f"capture: {', '.join(lifted)}")

    # --- guards first, for EVERY card, before one byte is written -----------
    problems, plan = [], []
    for c in cards:
        if c["block"] == "bespoke":
            continue
        try:
            blk = load_block(c["block"])
            validate(c, blk)
            problems += check_job(c)
            problems += check_trace(c, article)
            problems += check_dead_trace(c)
            problems += check_converted_odds(c)
            plan.append((c, blk))
        except Halt as e:
            problems.append(str(e))
    problems += check_mix(cards)
    if problems:
        print(f"AUTHORING HALTED — {len(problems)} problem(s):", file=sys.stderr)
        for p in problems:
            print(f"  ✗ {p}", file=sys.stderr)
        sys.exit(2)

    os.makedirs(a.out_dir, exist_ok=True)
    wrote, redone, skipped = [], [], []
    for c, blk in plan:
        frame_tpl = load_frame(c.get("layout", "fullscreen"))
        page = render_card(c, blk, frame_tpl)
        assert_no_invented_text(page, c, frame_tpl, blk)
        assert_measured_items_show_a_figure(c, blk)
        out = os.path.join(a.out_dir, c["page"])
        if os.path.exists(out):
            existing = open(out, encoding="utf-8").read()
            # A HAND-AUTHORED PAGE IS NEVER TOUCHED, not even with --force.
            # This check comes first on purpose: bespoke pages are the one thing
            # a blanket re-author would destroy.
            if MARKER not in existing:
                skipped.append((c["id"], c["page"], "hand-authored (no generated marker)"))
                continue
            # 🔴 THE --force TRAP, CLOSED. This used to read "already generated —
            # pass --force to redo", and the ENGINE NEVER PASSES --force. So
            # changing episode.json and clearing the flag re-checked the STALE
            # HTML and returned a byte-identical halt.
            #
            #     A CORRECT FIX LOOKED LIKE A FAILED ONE, TWICE.
            #
            # It broke nothing. It made the truth invisible — and the natural
            # next move is to undo a change that was right, or hunt a second
            # cause that is not there. On EP16 a layout fix moved a box from
            # (204,838) to (110,787) and NOTHING SHOWED IT, because the page on
            # disk was never rewritten.
            #
            # THE FIX IS DERIVED, NOT A LIST AND NOT A TIMESTAMP: the freshly
            # rendered page is already in hand, so COMPARE IT. If it differs, the
            # card's definition changed and the page is rewritten. If it is
            # identical, there was nothing to do anyway. Nothing to keep in sync,
            # nothing anyone must remember to bump, and it cannot go stale —
            # because the comparison IS the definition. (CLAUDE.md fault #7.)
            if existing == page and not a.force:
                skipped.append((c["id"], c["page"],
                                "unchanged — episode.json still says the same thing"))
                continue
            redone.append(c["page"])
        open(out, "w", encoding="utf-8", newline="\n").write(page)
        wrote.append(c["page"])

    for c in cards:
        if c["block"] == "bespoke":
            skipped.append((c["id"], c.get("page", "?"), "block:bespoke — hand-authored by design"))

    # SAY WHICH PAGES WERE RE-AUTHORED, not just how many were written. The whole
    # cost of the --force trap was that a regeneration and a no-op looked
    # identical from the outside.
    print(f"authored {len(wrote)} card page(s) into {a.out_dir}"
          + (f" ({len(redone)} REDONE because the card changed)" if redone else ""))
    for p in wrote:
        print(f"  {'~' if p in redone else '+'} {p}"
              + ("  (re-authored — its definition changed)" if p in redone else ""))
    for cid, page, why in skipped:
        print(f"  · {cid} {page} — left alone: {why}")
    # Untidy-but-harmless citations go in the RUN LOG, never in a gate — see the note
    # in preflight_cards.preflight_cards() for why they are not warnings.
    for c in cards:
        for s in check_stray_trace(c):
            print(f"  · {s}")


if __name__ == "__main__":
    try:
        main()
    except Halt as e:
        print(f"AUTHORING HALTED — {e}", file=sys.stderr)
        sys.exit(2)
